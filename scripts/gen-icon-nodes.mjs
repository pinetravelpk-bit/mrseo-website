// Regenerates src/components/blog/iconNodes.ts from lucide-react for the icons blog posts use.
// Usage: node scripts/gen-icon-nodes.mjs
import fs from 'node:fs';
const names = ['award','user-check','wrench','messages-square','laptop','store','wallet','trophy','train-front','map-pin','cpu','file-code','shopping-bag','shopping-cart','map','file-text','link','search-check','link-2','building-2','stethoscope','smile','scale','utensils','bed-double','plane','graduation-cap','cloud','globe','locate-fixed','landmark','house','building','git-compare','users','rocket','banknote','bot','sparkles','search'];
const out = {};
for (const n of names) {
  const src = fs.readFileSync(`node_modules/lucide-react/dist/esm/icons/${n}.js`, 'utf8');
  const arr = src.match(/const __iconNode = (\[[\s\S]*?\]);\n/)[1];
  out[n] = Function(`return ${arr}`)().map(([t, a]) => { const { key, ...rest } = a; return [t, rest]; });
}
fs.writeFileSync('src/components/blog/iconNodes.ts',
  '// Generated by scripts/gen-icon-nodes.mjs from lucide-react (ISC licence). Do not edit by hand.\n' +
  'export const ICON_NODES: Record<string, [string, Record<string, string>][]> = ' + JSON.stringify(out) + ';\n');
console.log('icons', Object.keys(out).length);
